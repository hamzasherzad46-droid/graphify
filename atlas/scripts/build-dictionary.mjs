// Builds data/dictionary.json: Atlas's approved spelling dictionary.
//
//   base          British English (-ise), from dictionary-en-gb (used through nspell; not copied in)
//   terminologia  every word of every Terminologia Anatomica term (TA98 and TA2), English converted to British spelling,
//                 Latin as published (data/sources/terminologia.json, from Wikidata, CC0)
//   approved      words a person has approved (names, abbreviations, terms outside TA)
//   proposed      words Claude has added, awaiting approval: they pass the check but are listed in every report
//   decisions     spelling choices made once and enforced everywhere (each wrong form fails the check)
//   historical    words accepted only in Gray's 1918 text (archaic but correct there: "lateralward")
//   forms         one form per word: the form on the left is never used ("antero-posterior" → "anteroposterior")
//   names         proper names kept exactly as their owners spell them ("Database Center for Life Science")
//   keep          British medical spellings that differ from general British spelling (specialty, sulfur)
//   corrections   typing errors in the imported books, by source, corrected on import ("symphisis" → "symphysis")
//
// Re-running keeps every hand-kept section as it is, and rebuilds `terminologia`.
//   node scripts/build-dictionary.mjs
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { known, setKnownWords, toBritish } from './lib/british.mjs'

const ROOT = join(import.meta.dirname, '..')
const OUT = join(ROOT, 'data', 'dictionary.json')
const ta = JSON.parse(readFileSync(join(ROOT, 'data', 'sources', 'terminologia.json'), 'utf8'))
const old = existsSync(OUT) ? JSON.parse(readFileSync(OUT, 'utf8')) : {}

const words = (s) => (s.match(/[A-Za-zÀ-ÿ]+(?:['’][A-Za-z]+)?/g) ?? []).map((w) => w.replace(/['’]s$/, '').toLowerCase()).filter((w) => w.length > 1)

// Latin first: those words are accepted as they are.
const latin = new Set(ta.terms.flatMap((t) => words(t.la)))
setKnownWords(latin)
// English names on Wikidata use American spelling ("esophagus"): each word goes in in its British form.
const english = new Set()
const converted = new Map()
for (const t of ta.terms)
  for (const w of words(t.en)) {
    const b = toBritish(w)
    if (b) converted.set(w, b.toLowerCase())
    english.add((b ?? w).toLowerCase())
  }
const terminologia = [...new Set([...latin, ...english])].sort()

const decisions = old.decisions ?? {
  fetus: { use: 'fetus', not: ['foetus'], why: 'Standard in British medical writing, and the en-GB dictionary’s form.' },
  fetal: { use: 'fetal', not: ['foetal'], why: 'As fetus.' },
  grey: { use: 'grey', not: ['gray'], why: 'British spelling; “Gray” stays only as the name (Henry Gray, Gray’s Anatomy).' },
  disc: { use: 'disc', not: ['disk'], why: 'British anatomical spelling (intervertebral disc, optic disc).' },
  ise: { use: '-ise', not: ['-ize'], why: 'One standard for the whole app (organise, recognise, ossification is unaffected).' },
}

const dict = {
  about: 'Atlas spelling dictionary. One standard: British English with -ise spellings. A word passes the text check (scripts/textcheck.mjs) if it is in the base dictionary, in terminologia, approved or proposed. Generated by scripts/build-dictionary.mjs; edit approved, proposed and decisions by hand.',
  base: { package: 'dictionary-en-gb', version: JSON.parse(readFileSync(join(ROOT, 'node_modules', 'dictionary-en-gb', 'package.json'), 'utf8')).version, licence: 'MIT AND BSD (SCOWL/hunspell en_GB)' },
  terminologia: {
    source: `Terminologia Anatomica (TA98 and TA2) via Wikidata, CC0; ${ta.count} terms, fetched ${ta.fetched}. English words converted to British spelling.`,
    convertedFromAmerican: Object.fromEntries([...converted].sort()),
    words: terminologia,
  },
  decisions,
  approved: old.approved ?? {},
  proposed: old.proposed ?? {},
  historical: old.historical ?? {},
  forms: old.forms ?? {},
  names: old.names ?? {},
  keep: old.keep ?? {},
  restricted: old.restricted ?? {},
  corrections: old.corrections ?? {},
}
writeFileSync(OUT, JSON.stringify(dict, null, 1) + '\n')
console.log(`${terminologia.length} terminologia words (${converted.size} converted to British); ${Object.keys(dict.approved).length} approved, ${Object.keys(dict.proposed).length} proposed`)
// Sanity: a few words every anatomy text uses.
for (const w of ['humerus', 'foramen', 'oesophagus', 'haemorrhage', 'sternocleidomastoid']) if (!known(w) && !terminologia.includes(w)) console.warn(`missing: ${w}`)
